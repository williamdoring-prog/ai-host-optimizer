/**
 * Accessory generators (M2b) — produce declarative implementation files from the
 * SAME registry the app uses, so they cannot drift.
 *
 * These functions are pure string builders; they write nothing and run nothing.
 * The generated Ansible playbook is check-mode friendly; the Dockerfile can only
 * set container environment (it cannot tune the host kernel — documented below).
 */

import type { OptimizationOption } from "./types.js";

/** Collect env vars from the selected options (same rule as the applier). */
function envFromOptions(selected: OptimizationOption[]): Record<string, string> {
  const env: Record<string, string> = {};
  for (const o of selected) {
    for (const [k, v] of Object.entries(o.env ?? {})) env[k] = v;
  }
  return env;
}

function header(kind: string, optionIds: string[]): string {
  return [
    `# ${kind} - generated by ai-host-optimizer`,
    `# Options: ${optionIds.length ? optionIds.join(", ") : "(none)"}`,
    "# Generated from the option registry; do not edit by hand.",
    "",
  ].join("\n");
}

/**
 * An Ansible playbook that writes the managed environment file.
 * Run with `--check --diff` first; it is idempotent and reversible.
 */
export function generateAnsible(selected: OptimizationOption[]): string {
  const env = envFromOptions(selected);
  const ids = selected.filter((o) => Object.keys(o.env ?? {}).length).map((o) => o.id);
  const lines = [header("Ansible playbook", ids)];
  lines.push("---");
  lines.push("- name: Configure the host for local AI inference");
  lines.push("  hosts: all");
  lines.push("  become: false            # user-space only; no privilege required");
  lines.push("  vars:");
  lines.push("    managed_dir: \"{{ ansible_env.HOME }}/.config/ai-host-optimizer\"");
  lines.push("  tasks:");
  lines.push("    - name: Ensure managed directory exists");
  lines.push("      ansible.builtin.file:");
  lines.push("        path: \"{{ managed_dir }}\"");
  lines.push("        state: directory");
  lines.push("        mode: \"0755\"");
  lines.push("");
  lines.push("    - name: Write managed environment file");
  lines.push("      ansible.builtin.copy:");
  lines.push("        dest: \"{{ managed_dir }}/ollama.env\"");
  lines.push("        mode: \"0644\"");
  lines.push("        content: |");
  lines.push("          # Generated by ai-host-optimizer");
  for (const [k, v] of Object.entries(env).sort()) {
    lines.push(`          export ${k}="${v}"`);
  }
  lines.push("");
  lines.push("    # To revert: delete the managed directory.");
  lines.push("    # NOTE: this playbook changes user-space configuration only.");
  lines.push("");
  return lines.join("\n");
}

/**
 * A Dockerfile that sets the environment for a container running the runtime.
 * NOTE: a container shares the host kernel, so this CANNOT apply host-level
 * tuning (zram, huge pages, CPU governor). Container-level only.
 */
export function generateDockerfile(selected: OptimizationOption[]): string {
  const env = envFromOptions(selected);
  const ids = selected.filter((o) => Object.keys(o.env ?? {}).length).map((o) => o.id);
  const lines = [header("Dockerfile", ids)];
  lines.push("FROM ollama/ollama:latest");
  lines.push("");
  lines.push("# Container-level environment only. Host-kernel tuning is NOT possible");
  lines.push("# from inside a container (see the project docs).");
  for (const [k, v] of Object.entries(env).sort()) {
    lines.push(`ENV ${k}=${v}`);
  }
  lines.push("");
  return lines.join("\n");
}

/** A printable Markdown checklist of every option (optionally filtered). */
export function generateChecklistMarkdown(options: OptimizationOption[]): string {
  const lines = ["# AI host optimization checklist", ""];
  for (const o of options) {
    const est =
      o.expectedImprovement.estimate !== undefined
        ? `${Math.round(o.expectedImprovement.estimate * 100)}%`
        : "qualitative";
    lines.push(`- [ ] **${o.name}** (\`${o.id}\`)`);
    lines.push(`  - improves: ${o.expectedImprovement.metric} — ${est} (tier ${o.expectedImprovement.tier})`);
    lines.push(`  - risk: ${o.risk}; reversibility: ${o.reversibility}; privilege: ${o.requiresPrivilege}`);
    if (o.exclusiveGroup) lines.push(`  - one-of group: \`${o.exclusiveGroup}\``);
    if (o.inclusiveGroup) lines.push(`  - stackable group: \`${o.inclusiveGroup}\``);
    if (o.conflictsWith.length) lines.push(`  - conflicts with: ${o.conflictsWith.join(", ")}`);
    if (o.requires.length) lines.push(`  - requires: ${o.requires.join(", ")}`);
    lines.push("");
  }
  return lines.join("\n");
}
