/**
 * Applier (M1) — applies selected, user-space options by writing files into a
 * MANAGED config directory. It never touches system files, never runs a shell,
 * never escalates privilege, and is fully reversible.
 *
 * Design commitments (see SECURITY.md):
 *   1. consent-driven (the caller passes an explicit plan),
 *   2. dry-run by default,
 *   3. reversible (state.json records what we wrote),
 *   4. allow-listed (only the ops in this file),
 *   5. injection-resistant (no shell; content is generated, not executed).
 */

import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";

import type { OptimizationOption } from "./types.js";
import { detectPlatform } from "./profiler.js";

const MANAGED_DIR_NAME = "ai-host-optimizer";

/** The managed config directory (platform-appropriate). */
export function managedDir(): string {
  const platform = detectPlatform();
  if (platform === "windows") {
    return join(process.env["APPDATA"] ?? homedir(), MANAGED_DIR_NAME);
  }
  if (platform === "macos") {
    return join(homedir(), "Library", "Application Support", MANAGED_DIR_NAME);
  }
  return join(process.env["XDG_CONFIG_HOME"] ?? join(homedir(), ".config"), MANAGED_DIR_NAME);
}

export interface ManagedFile {
  path: string;
  content: string;
}

export interface ApplyPlan {
  /** Allow-listed op ids contributing to this plan (e.g. "env", "systemd-dropin"). */
  ops: string[];
  /** Environment variables merged across all targets (for display). */
  envVars: Record<string, string>;
  /** Environment variables grouped by target runtime. */
  envByTarget: Record<string, Record<string, string>>;
  /** Files that would be written. */
  files: ManagedFile[];
  /** Option ids contributing to this plan. */
  optionIds: string[];
  /** Manual steps the user must run (the applier never escalates privilege). */
  notes: string[];
}

export interface ApplyResult {
  dryRun: boolean;
  written: string[];
}

export interface RevertResult {
  removed: string[];
}

/** Token replaced by the managed directory in env values. */
const MANAGED_DIR_TOKEN = "${MANAGED_DIR}";

/** Options that contribute environment for a managed runtime. */
function envOptions(options: OptimizationOption[]): OptimizationOption[] {
  return options.filter((o) => o.applyOp === "env" && o.env && Object.keys(o.env).length > 0);
}

/** Options that request a systemd drop-in for the Ollama service (Linux). */
function systemdOptions(options: OptimizationOption[]): OptimizationOption[] {
  return options.filter((o) => o.applyOp === "systemd-dropin");
}

/** Relative path of the Ollama systemd drop-in inside the managed dir. */
const SYSTEMD_DROPIN_REL = join("systemd", "ollama.service.d", "10-ai-host-optimizer.conf");

/**
 * A systemd drop-in that loads the managed Ollama environment into the Ollama
 * service. We write it into the managed directory; installing it into
 * /etc/systemd/system needs root, so that step is left to the user (printed as a
 * note). The applier never escalates privilege.
 */
function renderSystemdDropin(dir: string): string {
  return [
    "# Generated by ai-host-optimizer. Managed file - do not edit by hand.",
    "# Loads the managed Ollama environment into the Ollama service.",
    "[Service]",
    `EnvironmentFile=-${join(dir, "ollama.env")}`,
    "",
  ].join("\n");
}

/** Substitute `${MANAGED_DIR}` in an env value. */
function resolveValue(value: string, dir: string): string {
  return value.split(MANAGED_DIR_TOKEN).join(dir);
}

function renderEnvFile(target: string, vars: Record<string, string>, dir: string): string {
  const lines = [
    `# Generated by ai-host-optimizer. Managed file (target: ${target}) - do not edit by hand.`,
    "# Activate with:  source <this file>   (bash/zsh)   or set the vars manually.",
    "",
  ];
  for (const [k, v] of Object.entries(vars).sort()) {
    lines.push(`export ${k}="${resolveValue(v, dir)}"`);
  }
  lines.push("");
  return lines.join("\n");
}

function renderActivateSh(envFiles: string[]): string {
  const lines = [
    "#!/usr/bin/env sh",
    "# Generated by ai-host-optimizer. Sources the managed runtime environments.",
    `# shellcheck disable=SC1090`,
  ];
  for (const f of envFiles) lines.push(`. "${f}"`);
  lines.push("");
  return lines.join("\n");
}

function renderActivatePs1(allVars: Record<string, string>, dir: string): string {
  const lines = ["# Generated by ai-host-optimizer. Dot-source this file to activate."];
  for (const [k, v] of Object.entries(allVars).sort()) {
    lines.push(`$env:${k} = "${resolveValue(v, dir)}"`);
  }
  lines.push("");
  return lines.join("\n");
}

/**
 * Build an apply plan from selected option ids. Pure — performs no writes.
 *
 * Every selected option that declares `env` contributes to one or more target
 * runtimes; the applier writes one `<target>.env` file per runtime, plus a
 * single `activate.sh` / `activate.ps1` that sources them all.
 */
export function buildApplyPlan(
  selectedIds: string[],
  options: OptimizationOption[],
): ApplyPlan {
  const byId = new Map(options.map((o) => [o.id, o]));
  const selected = selectedIds
    .map((id) => byId.get(id))
    .filter((o): o is OptimizationOption => o !== undefined);

  const envContrib = envOptions(selected);
  const systemdContrib = systemdOptions(selected);

  // target runtime -> { NAME: value }
  const envByTarget: Record<string, Record<string, string>> = {};
  for (const o of envContrib) {
    for (const [target, vars] of Object.entries(o.env ?? {})) {
      envByTarget[target] ??= {};
      for (const [k, v] of Object.entries(vars)) envByTarget[target]![k] = v;
    }
  }

  const merged: Record<string, string> = {};
  for (const vars of Object.values(envByTarget)) Object.assign(merged, vars);

  const dir = managedDir();
  const targets = Object.keys(envByTarget).sort();
  const envPaths = targets.map((t) => join(dir, `${t}.env`));

  const ops: string[] = [];
  const files: ManagedFile[] = [];
  const notes: string[] = [];

  if (targets.length > 0) {
    ops.push("env");
    files.push(
      ...targets.map((t, i) => ({
        path: envPaths[i]!,
        content: renderEnvFile(t, envByTarget[t]!, dir),
      })),
      { path: join(dir, "activate.sh"), content: renderActivateSh(envPaths) },
      { path: join(dir, "activate.ps1"), content: renderActivatePs1(merged, dir) },
    );
  }

  if (systemdContrib.length > 0) {
    ops.push("systemd-dropin");
    const dropinPath = join(dir, SYSTEMD_DROPIN_REL);
    files.push({ path: dropinPath, content: renderSystemdDropin(dir) });
    notes.push(
      "To activate the systemd drop-in (needs root — run these yourself):",
      `  sudo mkdir -p /etc/systemd/system/ollama.service.d`,
      `  sudo cp "${dropinPath}" /etc/systemd/system/ollama.service.d/`,
      `  sudo systemctl daemon-reload && sudo systemctl restart ollama`,
    );
  }

  return {
    ops,
    envVars: merged,
    envByTarget,
    files,
    optionIds: [...new Set([...envContrib, ...systemdContrib].map((o) => o.id))],
    notes,
  };
}

/** Path of the state file. */
function statePath(): string {
  return join(managedDir(), "state.json");
}

interface State {
  version: 1;
  appliedAt: string;
  ops: string[];
  optionIds: string[];
  files: string[];
}

/**
 * Apply a plan. With `dryRun` (default true), nothing is written.
 * Only files inside the managed directory are ever written.
 */
export async function applyPlan(plan: ApplyPlan, dryRun = true): Promise<ApplyResult> {
  const dir = managedDir();

  if (plan.files.length === 0) {
    return { dryRun, written: [] };
  }

  if (dryRun) {
    return { dryRun: true, written: plan.files.map((f) => f.path) };
  }

  await mkdir(dir, { recursive: true });
  const written: string[] = [];
  for (const f of plan.files) {
    // Files may live in subdirectories (e.g. the systemd drop-in).
    await mkdir(dirname(f.path), { recursive: true });
    await writeFile(f.path, f.content, "utf8");
    written.push(f.path);
  }

  const state: State = {
    version: 1,
    appliedAt: new Date().toISOString(),
    ops: plan.ops,
    optionIds: plan.optionIds,
    files: written,
  };
  await writeFile(statePath(), JSON.stringify(state, null, 2), "utf8");
  written.push(statePath());

  return { dryRun: false, written };
}

/** Read the recorded state, if any. */
export async function readState(): Promise<State | undefined> {
  try {
    const raw = await readFile(statePath(), "utf8");
    return JSON.parse(raw) as State;
  } catch {
    return undefined;
  }
}

/**
 * Revert: remove the files recorded in state. Only files inside the managed
 * directory are removed. Idempotent — a second revert reports nothing, and the
 * state file itself is cleared.
 */
export async function revert(): Promise<RevertResult> {
  const state = await readState();
  if (!state) return { removed: [] };

  const dir = managedDir();
  const removed: string[] = [];
  for (const f of [...state.files, statePath()]) {
    // Safety: only remove files inside the managed dir.
    if (!f.startsWith(dir)) continue;
    try {
      await stat(f); // only report files that actually exist (idempotent)
    } catch {
      continue;
    }
    try {
      await rm(f, { force: true });
      removed.push(f);
    } catch {
      // ignore
    }
  }
  return { removed };
}
