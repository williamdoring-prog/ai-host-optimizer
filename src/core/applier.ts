/**
 * Applier (M1) — applies selected, user-space options by writing files into a
 * MANAGED config directory. It never touches system files, never runs a shell,
 * never escalates privilege, and is fully reversible.
 *
 * Design commitments (see SECURITY.md):
 *   1. consent-driven (the caller passes an explicit plan),
 *   2. dry-run by default,
 *   3. reversible (state.json records what we wrote),
 *   4. allow-listed (only the ops in this file),
 *   5. injection-resistant (no shell; content is generated, not executed).
 */

import { homedir } from "node:os";
import { join } from "node:path";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";

import type { OptimizationOption } from "./types.js";
import { detectPlatform } from "./profiler.js";

const MANAGED_DIR_NAME = "ai-host-optimizer";

/** The managed config directory (platform-appropriate). */
export function managedDir(): string {
  const platform = detectPlatform();
  if (platform === "windows") {
    return join(process.env["APPDATA"] ?? homedir(), MANAGED_DIR_NAME);
  }
  if (platform === "macos") {
    return join(homedir(), "Library", "Application Support", MANAGED_DIR_NAME);
  }
  return join(process.env["XDG_CONFIG_HOME"] ?? join(homedir(), ".config"), MANAGED_DIR_NAME);
}

export interface ManagedFile {
  path: string;
  content: string;
}

export interface ApplyPlan {
  /** Allow-listed op id. */
  op: string;
  /** Environment variables contributed by the selected options. */
  envVars: Record<string, string>;
  /** Files that would be written. */
  files: ManagedFile[];
  /** Option ids contributing to this plan. */
  optionIds: string[];
}

export interface ApplyResult {
  dryRun: boolean;
  written: string[];
}

export interface RevertResult {
  removed: string[];
}

/** Options that map to the managed Ollama environment. */
function ollamaEnvOptions(options: OptimizationOption[]): OptimizationOption[] {
  return options.filter((o) => o.applyOp === "ollama-env" && o.env);
}

function renderEnvFile(envVars: Record<string, string>): string {
  const lines = [
    "# Generated by ai-host-optimizer. Managed file - do not edit by hand.",
    "# Activate with:  source <this file>   (bash/zsh)   or set the vars manually.",
    "",
  ];
  for (const [k, v] of Object.entries(envVars).sort()) {
    lines.push(`export ${k}="${v}"`);
  }
  lines.push("");
  return lines.join("\n");
}

function renderActivateSh(envFile: string): string {
  return [
    "#!/usr/bin/env sh",
    "# Generated by ai-host-optimizer. Sources the managed environment.",
    `# shellcheck disable=SC1090`,
    `. "${envFile}"`,
    "",
  ].join("\n");
}

function renderActivatePs1(envVars: Record<string, string>): string {
  const lines = [
    "# Generated by ai-host-optimizer. Dot-source this file to activate.",
  ];
  for (const [k, v] of Object.entries(envVars).sort()) {
    lines.push(`$env:${k} = "${v}"`);
  }
  lines.push("");
  return lines.join("\n");
}

/**
 * Build an apply plan from selected option ids. Pure — performs no writes.
 */
export function buildApplyPlan(
  selectedIds: string[],
  options: OptimizationOption[],
): ApplyPlan {
  const byId = new Map(options.map((o) => [o.id, o]));
  const selected = selectedIds
    .map((id) => byId.get(id))
    .filter((o): o is OptimizationOption => o !== undefined);

  const contributing = ollamaEnvOptions(selected);
  const envVars: Record<string, string> = {};
  for (const o of contributing) {
    for (const [k, v] of Object.entries(o.env ?? {})) envVars[k] = v;
  }

  const dir = managedDir();
  const envPath = join(dir, "ollama.env");
  const files: ManagedFile[] = [
    { path: envPath, content: renderEnvFile(envVars) },
    { path: join(dir, "activate.sh"), content: renderActivateSh(envPath) },
    { path: join(dir, "activate.ps1"), content: renderActivatePs1(envVars) },
  ];

  return {
    op: "ollama-env",
    envVars,
    files,
    optionIds: contributing.map((o) => o.id),
  };
}

/** Path of the state file. */
function statePath(): string {
  return join(managedDir(), "state.json");
}

interface State {
  version: 1;
  appliedAt: string;
  op: string;
  optionIds: string[];
  files: string[];
}

/**
 * Apply a plan. With `dryRun` (default true), nothing is written.
 * Only files inside the managed directory are ever written.
 */
export async function applyPlan(plan: ApplyPlan, dryRun = true): Promise<ApplyResult> {
  const dir = managedDir();

  if (Object.keys(plan.envVars).length === 0) {
    return { dryRun, written: [] };
  }

  if (dryRun) {
    return { dryRun: true, written: plan.files.map((f) => f.path) };
  }

  await mkdir(dir, { recursive: true });
  const written: string[] = [];
  for (const f of plan.files) {
    await writeFile(f.path, f.content, "utf8");
    written.push(f.path);
  }

  const state: State = {
    version: 1,
    appliedAt: new Date().toISOString(),
    op: plan.op,
    optionIds: plan.optionIds,
    files: written,
  };
  await writeFile(statePath(), JSON.stringify(state, null, 2), "utf8");
  written.push(statePath());

  return { dryRun: false, written };
}

/** Read the recorded state, if any. */
export async function readState(): Promise<State | undefined> {
  try {
    const raw = await readFile(statePath(), "utf8");
    return JSON.parse(raw) as State;
  } catch {
    return undefined;
  }
}

/**
 * Revert: remove the files recorded in state. Only files inside the managed
 * directory are removed.
 */
export async function revert(): Promise<RevertResult> {
  const state = await readState();
  if (!state) return { removed: [] };

  const dir = managedDir();
  const removed: string[] = [];
  for (const f of state.files) {
    // Safety: only remove files inside the managed dir.
    if (!f.startsWith(dir)) continue;
    try {
      await rm(f, { force: true });
      removed.push(f);
    } catch {
      // ignore
    }
  }
  return { removed };
}
