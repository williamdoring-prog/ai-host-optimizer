/**
 * Applier — applies selected, user-space options by writing files into a MANAGED
 * config directory. It never touches system files, never runs a shell, never
 * escalates privilege, and is fully reversible.
 *
 * Design commitments (see SECURITY.md):
 *   1. consent-driven (the caller passes a resolved, conflict-free plan),
 *   2. dry-run by default,
 *   3. reversible (state.json records what we wrote, and backs up what existed),
 *   4. allow-listed (only the ops in applyops.ts),
 *   5. injection-resistant (no shell; values are sink-encoded, never executed),
 *   6. contained (every write/delete path is proven inside the managed dir).
 */

import { dirname, join, relative } from "node:path";
import { mkdir, open, readFile, rename, rm, stat } from "node:fs/promises";

import type { OptimizationOption } from "./types.js";
import type { ApplyOpId } from "./applyops.js";
import type { Plan } from "./plan.js";
import { managedDir, resolveManagedToken } from "./paths.js";
import { mergeEnvByTarget, flattenEnv } from "./env.js";
import { ENV_NAME_RE, TARGET_NAME_RE, assertContained, isContained } from "./safety.js";
import {
  encodePowerShellDoubleQuoted,
  encodeShDoubleQuoted,
} from "../render/encoding.js";

export interface ManagedFile {
  path: string;
  content: string;
}

export interface ApplyPlan {
  /** Allow-listed op ids contributing to this plan (e.g. "env", "systemd-dropin"). */
  ops: ApplyOpId[];
  /** Environment variables merged across all targets (for display). */
  envVars: Record<string, string>;
  /** Environment variables grouped by target runtime. */
  envByTarget: Record<string, Record<string, string>>;
  /** Files that would be written. */
  files: ManagedFile[];
  /** Option ids contributing to this plan. */
  optionIds: string[];
  /** Environment variable names whose values must be redacted in output. */
  secretVars: string[];
  /** Manual steps the user must run (the applier never escalates privilege). */
  notes: string[];
}

export interface ApplyResult {
  dryRun: boolean;
  written: string[];
}

export interface RevertResult {
  removed: string[];
}

/** One file tracked by the state file. */
export interface StateFileEntry {
  path: string;
  /** Absolute path of the backup taken before we first wrote this file, if it pre-existed. */
  backup?: string;
}

export interface State {
  version: 2;
  appliedAt: string;
  ops: string[];
  optionIds: string[];
  files: StateFileEntry[];
}

/** Options that contribute environment for a managed runtime (env + numeric size). */
function envOptions(options: OptimizationOption[]): OptimizationOption[] {
  return options.filter(
    (o) => (o.applyOp === "env" || o.applyOp === "size") && o.env && Object.keys(o.env).length > 0,
  );
}

/** Options that request a systemd drop-in for the Ollama service (Linux). */
function systemdOptions(options: OptimizationOption[]): OptimizationOption[] {
  return options.filter((o) => o.applyOp === "systemd-dropin");
}

/** Relative path of the Ollama systemd drop-in inside the managed dir. */
const SYSTEMD_DROPIN_REL = join("systemd", "ollama.service.d", "10-ai-host-optimizer.conf");

/**
 * A systemd drop-in that loads the managed Ollama environment into the Ollama
 * service. We write it into the managed directory; installing it into
 * /etc/systemd/system needs root, so that step is left to the user (printed as a
 * note). The applier never escalates privilege.
 */
function renderSystemdDropin(dir: string): string {
  return [
    "# Generated by ai-host-optimizer. Managed file - do not edit by hand.",
    "# Loads the managed Ollama environment into the Ollama service.",
    "[Service]",
    `EnvironmentFile=-${join(dir, "ollama.env")}`,
    "",
  ].join("\n");
}

/** Substitute `${MANAGED_DIR}` in an env value. */
function resolveValue(value: string, dir: string): string {
  return resolveManagedToken(value, dir);
}

function renderEnvFile(target: string, vars: Record<string, string>, dir: string): string {
  const lines = [
    `# Generated by ai-host-optimizer. Managed file (target: ${target}) - do not edit by hand.`,
    "# Activate with:  source <this file>   (bash/zsh)   or set the vars manually.",
    "",
  ];
  for (const [k, v] of Object.entries(vars).sort()) {
    lines.push(`export ${k}="${encodeShDoubleQuoted(resolveValue(v, dir))}"`);
  }
  lines.push("");
  return lines.join("\n");
}

function renderActivateSh(envFiles: string[]): string {
  const lines = [
    "#!/usr/bin/env sh",
    "# Generated by ai-host-optimizer. Sources the managed runtime environments.",
    `# shellcheck disable=SC1090`,
  ];
  for (const f of envFiles) lines.push(`. "${encodeShDoubleQuoted(f)}"`);
  lines.push("");
  return lines.join("\n");
}

function renderActivatePs1(allVars: Record<string, string>, dir: string): string {
  const lines = ["# Generated by ai-host-optimizer. Dot-source this file to activate."];
  for (const [k, v] of Object.entries(allVars).sort()) {
    lines.push(`$env:${k} = "${encodePowerShellDoubleQuoted(resolveValue(v, dir))}"`);
  }
  lines.push("");
  return lines.join("\n");
}

/**
 * Build an apply plan from a **resolved** `Plan`. Pure — performs no writes.
 *
 * Taking a `Plan` (not raw ids) is deliberate: the plan has already applied
 * applicability and conflict rules, so a non-applicable or conflicting option
 * cannot be materialised here even if a caller asks for it.
 *
 * Every selected option that declares `env` contributes to one or more target
 * runtimes; the applier writes one `<target>.env` file per runtime, plus a
 * single `activate.sh` / `activate.ps1` that sources them all.
 */
export function buildApplyPlan(plan: Plan, dir = managedDir()): ApplyPlan {
  const selected = plan.steps.map((s) => s.option);

  const envContrib = envOptions(selected);
  const systemdContrib = systemdOptions(selected);

  // Validate target/name shape (defence in depth; validateRegistry covers it).
  for (const o of envContrib) {
    for (const [target, vars] of Object.entries(o.env ?? {})) {
      if (!TARGET_NAME_RE.test(target)) {
        throw new Error(`${o.id}: invalid env target name "${target}"`);
      }
      for (const k of Object.keys(vars)) {
        if (!ENV_NAME_RE.test(k)) throw new Error(`${o.id}: invalid env variable name "${k}"`);
      }
    }
  }

  const envByTarget = mergeEnvByTarget(envContrib);
  const merged = flattenEnv(envContrib);

  const targets = Object.keys(envByTarget).sort();
  const envPaths = targets.map((t) => join(dir, `${t}.env`));

  const ops: ApplyOpId[] = [];
  const files: ManagedFile[] = [];
  const notes: string[] = [];

  if (targets.length > 0) {
    ops.push("env");
    if (envContrib.some((o) => o.applyOp === "size")) ops.push("size");
    files.push(
      ...targets.map((t, i) => ({
        path: envPaths[i]!,
        content: renderEnvFile(t, envByTarget[t]!, dir),
      })),
      { path: join(dir, "activate.sh"), content: renderActivateSh(envPaths) },
      { path: join(dir, "activate.ps1"), content: renderActivatePs1(merged, dir) },
    );
  }

  if (systemdContrib.length > 0) {
    ops.push("systemd-dropin");
    const dropinPath = join(dir, SYSTEMD_DROPIN_REL);
    files.push({ path: dropinPath, content: renderSystemdDropin(dir) });
    notes.push(
      "To activate the systemd drop-in (needs root — run these yourself):",
      `  sudo mkdir -p /etc/systemd/system/ollama.service.d`,
      `  sudo cp "${dropinPath}" /etc/systemd/system/ollama.service.d/`,
      `  sudo systemctl daemon-reload && sudo systemctl restart ollama`,
      "To remove it later:",
      `  sudo rm -f /etc/systemd/system/ollama.service.d/10-ai-host-optimizer.conf`,
      `  sudo systemctl daemon-reload && sudo systemctl restart ollama`,
    );
  }

  // Containment is proven here, before anything can be written.
  for (const f of files) assertContained(dir, f.path);

  const secretVars = [
    ...new Set(
      envContrib
        .filter((o) => o.secret)
        .flatMap((o) => Object.values(o.env ?? {}).flatMap((vars) => Object.keys(vars))),
    ),
  ];

  return {
    ops,
    envVars: merged,
    envByTarget,
    files,
    optionIds: [...new Set([...envContrib, ...systemdContrib].map((o) => o.id))],
    secretVars,
    notes,
  };
}

/** Path of the state file. */
function statePath(dir = managedDir()): string {
  return join(dir, "state.json");
}

/** Directory holding backups of files that pre-existed an apply. */
function backupDir(dir = managedDir()): string {
  return join(dir, "backups");
}

/** Deterministic, contained backup path for a managed file. */
function backupPathFor(file: string, dir: string): string {
  const encoded = Buffer.from(relative(dir, file), "utf8").toString("base64url");
  return join(backupDir(dir), `${encoded}.bak`);
}

/** Read a file, returning undefined when it does not exist. */
async function readFileSafe(path: string): Promise<string | undefined> {
  try {
    return await readFile(path, "utf8");
  } catch {
    return undefined;
  }
}

/**
 * Write `content` atomically: temp file → fsync → rename. A crash leaves either
 * the old file or the new one, never a half-written file.
 */
async function writeFileAtomic(path: string, content: string): Promise<void> {
  const tmp = `${path}.tmp-${process.pid}-${Date.now()}-${Math.random().toString(16).slice(2)}`;
  // 0600: only the owner can read/write the managed files (ignored on Windows).
  const handle = await open(tmp, "w", 0o600);
  try {
    await handle.writeFile(content, "utf8");
    await handle.sync();
  } finally {
    await handle.close();
  }
  try {
    await rename(tmp, path);
  } catch (err) {
    await rm(tmp, { force: true });
    throw err;
  }
}

/** Normalise a parsed state file (accepting the v1 `files: string[]` shape). */
function normalizeState(parsed: unknown): State {
  if (!parsed || typeof parsed !== "object") {
    throw new Error("managed state file is corrupt: not an object");
  }
  const obj = parsed as Record<string, unknown>;
  const filesRaw = obj["files"];
  if (!Array.isArray(filesRaw)) {
    throw new Error("managed state file is corrupt: missing file list");
  }
  const files: StateFileEntry[] = filesRaw.map((f) => {
    if (typeof f === "string") return { path: f }; // v1 shape
    if (f && typeof f === "object" && typeof (f as { path?: unknown }).path === "string") {
      const entry = f as { path: string; backup?: unknown };
      return { path: entry.path, backup: typeof entry.backup === "string" ? entry.backup : undefined };
    }
    throw new Error("managed state file is corrupt: bad file entry");
  });
  const strings = (value: unknown): string[] =>
    Array.isArray(value) ? value.filter((x): x is string => typeof x === "string") : [];
  return {
    version: 2,
    appliedAt: typeof obj["appliedAt"] === "string" ? obj["appliedAt"] : new Date(0).toISOString(),
    ops: strings(obj["ops"]),
    optionIds: strings(obj["optionIds"]),
    files,
  };
}

/**
 * Read the recorded state, if any. A corrupt state file is a hard error (never
 * silently ignored — that would strand files on disk).
 */
export async function readState(dir = managedDir()): Promise<State | undefined> {
  const path = statePath(dir);
  let raw: string;
  try {
    raw = await readFile(path, "utf8");
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === "ENOENT") return undefined;
    throw err;
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch (err) {
    throw new Error(`managed state file is corrupt (${path}): ${(err as Error).message}`);
  }
  return normalizeState(parsed);
}

/**
 * Apply a plan. With `dryRun` (default true), nothing is written.
 *
 * The state file accumulates the **union** of every file ever written, so
 * several applies followed by one revert removes them all. Files that already
 * existed are backed up before being overwritten, and restored on revert.
 */
export async function applyPlan(
  plan: ApplyPlan,
  dryRun = true,
  dir = managedDir(),
): Promise<ApplyResult> {
  if (plan.files.length === 0) {
    return { dryRun, written: [] };
  }
  for (const f of plan.files) assertContained(dir, f.path);

  if (dryRun) {
    return { dryRun: true, written: plan.files.map((f) => f.path) };
  }

  await mkdir(dir, { recursive: true, mode: 0o700 });
  const prior = await readState(dir); // throws on corrupt state — do not clobber it
  const merged = new Map<string, StateFileEntry>((prior?.files ?? []).map((e) => [e.path, e]));
  const written: string[] = [];

  for (const f of plan.files) {
    assertContained(dir, f.path);
    await mkdir(dirname(f.path), { recursive: true, mode: 0o700 });

    let entry = merged.get(f.path);
    if (!entry) {
      entry = { path: f.path };
      const existing = await readFileSafe(f.path);
      if (existing !== undefined) {
        const backup = backupPathFor(f.path, dir);
        await mkdir(dirname(backup), { recursive: true, mode: 0o700 });
        await writeFileAtomic(backup, existing);
        entry.backup = backup;
      }
    }

    await writeFileAtomic(f.path, f.content);
    merged.set(f.path, entry);
    written.push(f.path);
  }

  const state: State = {
    version: 2,
    appliedAt: new Date().toISOString(),
    ops: [...new Set([...(prior?.ops ?? []), ...plan.ops])],
    optionIds: [...new Set([...(prior?.optionIds ?? []), ...plan.optionIds])],
    files: [...merged.values()],
  };
  await writeFileAtomic(statePath(dir), JSON.stringify(state, null, 2));
  written.push(statePath(dir));

  return { dryRun: false, written };
}

/**
 * Revert: remove every file recorded in state (and restore any backups). Only
 * files inside the managed directory are touched. Idempotent — a second revert
 * reports nothing, and the state file itself is cleared.
 */
export async function revert(dir = managedDir()): Promise<RevertResult> {
  const state = await readState(dir);
  if (!state) return { removed: [] };

  const removed: string[] = [];

  for (const entry of state.files) {
    if (!isContained(dir, entry.path)) continue;

    // Restore a pre-existing file rather than deleting it.
    if (entry.backup && isContained(dir, entry.backup)) {
      const content = await readFileSafe(entry.backup);
      if (content !== undefined) {
        try {
          await writeFileAtomic(entry.path, content);
          await rm(entry.backup, { force: true });
          removed.push(entry.path);
          continue;
        } catch {
          // fall through to removal
        }
      }
    }

    try {
      await stat(entry.path); // only report files that actually exist (idempotent)
    } catch {
      continue;
    }
    try {
      await rm(entry.path, { force: true });
      removed.push(entry.path);
    } catch {
      // ignore
    }
  }

  const sp = statePath(dir);
  if (isContained(dir, sp)) {
    try {
      await stat(sp);
      await rm(sp, { force: true });
      removed.push(sp);
    } catch {
      // ignore
    }
  }

  return { removed };
}
